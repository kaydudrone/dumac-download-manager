// Bridges the extension to the local helper (host/dumac_host.py) and the Dumac Download Manager app.
const native = (msg) => new Promise((resolve) => chrome.runtime.sendNativeMessage('io.github.kaydudrone.dumac', msg, (res) =>
  resolve(chrome.runtime.lastError ? { error: 'Helper not installed. Run install.sh.' } : res)));

const isYouTube = (url) => /^https:\/\/([\w-]+\.)?(youtube\.com|youtu\.be)\//.test(url || '');

// Cookies the browser holds for url, so sites that need your login (Instagram, Facebook, file hosts) work.
// YouTube only with Options → "Use my YouTube login" (fixes "confirm you're not a bot"; off by default
// because downloading with a Google login can get the account flagged).
async function cookiesFor(url, settings) {
  if (isYouTube(url) ? !settings.youtube_login : !settings.use_browser_login) return [];
  try {
    const list = await chrome.cookies.getAll({ url });
    return list.map((c) => ({ name: c.name, value: c.value, domain: c.domain, path: c.path,
      secure: c.secure, hostOnly: c.hostOnly, expirationDate: c.expirationDate }));
  } catch {
    return [];
  }
}

// Requests from the "Download this video" buttons.
chrome.runtime.onMessage.addListener((msg, _sender, reply) => {
  (async () => {
    if (['formats', 'download'].includes(msg.type)) {
      const settings = await native({ type: 'settings_get' });
      msg = { ...msg, cookies: settings.error ? [] : await cookiesFor(msg.url, settings) };
    }
    reply(await native(msg));
  })();
  return true;
});

// Toolbar icon: open the Dumac Download Manager Mac app; without the app, open (or focus) the manager window here.
chrome.action.onClicked.addListener(async () => {
  const app = await native({ type: 'open_app' });
  if (app && app.ok) return;
  const url = chrome.runtime.getURL('manager.html');
  const [tab] = await chrome.tabs.query({ url });
  if (tab) {
    await chrome.windows.update(tab.windowId, { focused: true });
    return;
  }
  chrome.windows.create({ url, type: 'popup', width: 1100, height: 600 });
});

// Takeover: every http(s) download the browser starts goes to Dumac Download Manager instead.
// blob:/data: downloads (generated by the page itself) can't be fetched again, so the browser keeps those.
// If the helper is missing or Options → "Catch browser downloads" is off, the browser downloads as usual.
const handBack = new Set();  // downloads we re-start in the browser after a failed handover: don't catch them twice

chrome.downloads.onDeterminingFilename.addListener((item, suggest) => {
  const url = item.finalUrl || item.url;
  if (!/^https?:/i.test(url) || item.byExtensionId === chrome.runtime.id || handBack.has(url)) {
    handBack.delete(url);
    suggest();
    return;
  }
  (async () => {
    const settings = await native({ type: 'settings_get' });
    if (settings.error || !settings.catch_browser) { suggest(); return; }
    await chrome.downloads.cancel(item.id);
    suggest();
    chrome.downloads.erase({ id: item.id });
    const res = await native({
      type: 'catch', url, filename: (item.filename || '').split('/').pop(), referrer: item.referrer,
      ua: navigator.userAgent, cookies: await cookiesFor(url, settings),
    });
    if (res.ok) {
      native({ type: 'show_status', id: res.id });
    } else {
      handBack.add(url);
      chrome.downloads.download({ url });  // let the browser do it after all
    }
  })();
  return true;  // suggest() is called asynchronously
});
